// Pre-computes SVG paths for the East Africa locator maps (Natural Earth 1:50m via world-atlas).
// Output: src/assets/maps/east-africa.js  (sets window.TBPL_MAPS, so pages work from file://)
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const all = feature(topo, topo.objects.countries).features;

// ISO 3166 numeric codes
const NAMES = { '834': 'Tanzania', '404': 'Kenya', '800': 'Uganda', '508': 'Mozambique', '454': 'Malawi',
  '646': 'Rwanda', '108': 'Burundi', '180': 'DR Congo', '894': 'Zambia', '706': 'Somalia', '231': 'Ethiopia',
  '728': 'South Sudan', '716': 'Zimbabwe', '024': 'Angola', '450': 'Madagascar', '140': 'C.A.R.', '178': 'Congo' };

function build(width, height, bounds) {
  // Fit to the corner points (a Polygon would need spherical winding order).
  const clip = { type: 'MultiPoint', coordinates: [[bounds[0], bounds[1]], [bounds[2], bounds[1]], [bounds[2], bounds[3]], [bounds[0], bounds[3]]] };
  const proj = geoMercator().fitExtent([[0, 0], [width, height]], clip);
  const path = geoPath(proj);
  const countries = all.filter(f => NAMES[f.id]).map(f => ({ id: f.id, name: NAMES[f.id], d: path(f), c: proj(geoCentroidSafe(f)) }));
  return { width, height, countries, project: null, proj };
}
function geoCentroidSafe(f) { return geoPath().centroid(f); }

const regional = build(600, 640, [27, -19, 43, 5.5]);
const tanzania = build(600, 560, [29, -12.2, 40.6, -0.8]);

// Places named in Issue 001. Coordinates are approximate town centroids, for indicative location only.
const PLACES = {
  dar: { name: 'Dar es Salaam', lonlat: [39.28, -6.82] },
  kibaha: { name: 'Kibaha', lonlat: [38.92, -6.77] },
  morogoro: { name: 'Morogoro', lonlat: [37.66, -6.82] },
  dodoma: { name: 'Dodoma', lonlat: [35.74, -6.17] },
  tanga: { name: 'Tanga', lonlat: [39.10, -5.07] },
  chunya: { name: 'Chunya', lonlat: [33.43, -8.53] },
  njombe: { name: 'Njombe', lonlat: [34.77, -9.33] }
};
const out = {};
for (const [key, m] of Object.entries({ regional, tanzania })) {
  out[key] = { width: m.width, height: m.height,
    countries: m.countries.map(c => ({ id: c.id, name: c.name, d: c.d, cx: +c.c[0].toFixed(1), cy: +c.c[1].toFixed(1) })),
    places: Object.fromEntries(Object.entries(PLACES).map(([k, p]) => { const [x, y] = m.proj(p.lonlat); return [k, { name: p.name, x: +x.toFixed(1), y: +y.toFixed(1) }]; })) };
}
writeFileSync(new URL('../src/assets/maps/east-africa.js', import.meta.url),
  '/* Generated by scripts/build-maps.mjs from Natural Earth 1:50m (public domain). Do not edit. */\nwindow.TBPL_MAPS = ' + JSON.stringify(out) + ';\n');
console.log('maps written', Object.keys(out), out.regional.countries.map(c => c.name).join(', '));
